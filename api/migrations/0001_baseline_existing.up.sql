-- Baseline migration: makes Go migrations the authoritative source for
-- the four tables that existed before this project (created originally by
-- ../scryfall/load_scryfall.py and manual canonical_cards work).
--
-- This file uses CREATE TABLE IF NOT EXISTS so it is safe to apply against
-- either a fresh database or one that already has these tables.
--
-- For an existing database that already has these tables:
--   migrate -path ./migrations -database "mysql://..." force 1
-- That marks this migration as applied without re-running it.

CREATE TABLE IF NOT EXISTS sets (
  id              CHAR(36)     NOT NULL PRIMARY KEY,
  code            VARCHAR(16)  NOT NULL,
  name            VARCHAR(255) NOT NULL,
  set_type        VARCHAR(64),
  released_at     DATE,
  block_code      VARCHAR(16),
  block           VARCHAR(128),
  parent_set_code VARCHAR(16),
  card_count      INT,
  printed_size    INT,
  digital         TINYINT(1),
  foil_only       TINYINT(1),
  nonfoil_only    TINYINT(1),
  mtgo_code       VARCHAR(16),
  arena_code      VARCHAR(16),
  tcgplayer_id    BIGINT,
  scryfall_uri    VARCHAR(512),
  uri             VARCHAR(512),
  icon_svg_uri    VARCHAR(512),
  search_uri      VARCHAR(512),
  UNIQUE KEY uk_sets_code (code),
  INDEX idx_sets_released_at (released_at),
  INDEX idx_sets_type (set_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

