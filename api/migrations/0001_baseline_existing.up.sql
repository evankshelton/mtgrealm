CREATE TABLE IF NOT EXISTS canonical_cards (
  id                CHAR(36)     NOT NULL,
  oracle_id         CHAR(36)     NOT NULL,
  name              VARCHAR(512) NOT NULL,
  layout            VARCHAR(32),
  released_at       DATE,
  set_id            CHAR(36),
  set_code          VARCHAR(16),
  set_name          VARCHAR(255),
  set_type          VARCHAR(64),
  collector_number  VARCHAR(32),
  rarity            VARCHAR(32),
  cmc               FLOAT,
  mana_cost         VARCHAR(128),
  type_line         VARCHAR(255),
  oracle_text       TEXT,
  power             VARCHAR(16),
  toughness         VARCHAR(16),
  loyalty           VARCHAR(16),
  defense           VARCHAR(16),
  colors            JSON,
  color_identity    JSON,
  color_indicator   JSON,
  keywords          JSON,
  produced_mana     JSON,
  legalities        JSON,
  card_faces        JSON,
  edhrec_rank       INT,
  penny_rank        INT,
  artist            VARCHAR(255),
  flavor_text       TEXT,
  border_color      VARCHAR(32),
  frame             VARCHAR(16),
  illustration_id   CHAR(36),
  image_status      VARCHAR(32),
  image_uris        JSON,
  highres_image     TINYINT(1),
  reserved          TINYINT(1),
  full_art          TINYINT(1),
  booster           TINYINT(1),
  foil              TINYINT(1),
  nonfoil           TINYINT(1),
  tcgplayer_id      BIGINT,
  cardmarket_id     BIGINT,
  mtgo_id           BIGINT,
  scryfall_uri      VARCHAR(512),
  prices            JSON,
  purchase_uris     JSON,
  all_parts         JSON,
  updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
                                 ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (oracle_id),
  UNIQUE KEY uq_canonical_card_id (id),
  KEY idx_canonical_name (name(191)),
  KEY idx_canonical_set_code (set_code),
  KEY idx_canonical_set_type (set_type),
  KEY idx_canonical_cmc (cmc),
  KEY idx_canonical_rarity (rarity),
  KEY idx_canonical_tcgplayer_id (tcgplayer_id),
  KEY idx_canonical_edhrec_rank (edhrec_rank),
  KEY idx_canonical_released_at (released_at),
  CONSTRAINT fk_canonical_card_id FOREIGN KEY (id) REFERENCES cards (id)
    ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS load_meta (
  load_date     VARCHAR(20) NOT NULL PRIMARY KEY,
  cards_loaded  BIGINT,
  sets_loaded   INT,
  loaded_at     DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
